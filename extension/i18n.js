  // Language tag -> supported code; Traditional Chinese (zh-Hant, zh-TW, zh-HK, zh-MO) gets its own table.
  function matchLang(candidate) {
    if (!candidate) return null;
    const value = String(candidate).toLowerCase().replace(/_/g, "-").split(".")[0];
    if (LANGS.includes(value)) return value;
    const [primary, ...rest] = value.split("-");
    if (primary === "zh") return rest.some((part) => ["hant", "tw", "hk", "mo"].includes(part)) ? "zh-hant" : "zh";
    return LANGS.includes(primary) ? primary : null;
  }

  function detectLang() {
    const candidates = [];
    if (typeof navigator !== "undefined") {
      if (Array.isArray(navigator.languages)) candidates.push(...navigator.languages);
      if (navigator.language) candidates.push(navigator.language);
    }
    for (const candidate of candidates) {
      const match = matchLang(candidate);
      if (match) return match;
    }
    return "en";
  }

