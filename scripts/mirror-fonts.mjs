#!/usr/bin/env node
// Mirror the site's Google Fonts to R2 so visitors never contact Google.
//   node scripts/mirror-fonts.mjs            download every woff2 slice into dist-fonts/ and write site/fonts-<key>.css
//   node scripts/mirror-fonts.mjs --upload   also upload dist-fonts/ to R2 (wrangler, bucket ivjn, prefix cookie-sync/fonts/)
// Google only returns woff2 slices with unicode-range to a modern browser, hence the Chrome user agent.
import crypto from "node:crypto";
import { spawn } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "dist-fonts");
const BUCKET = "ivjn";
const PREFIX = "cookie-sync/fonts/";
const PUBLIC_BASE = "https://r2.ivjn.us/cookie-sync/fonts/";
const USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";
const CJK_WEIGHTS = "400;500;600;700;900";
const GSTATIC_URL = /url\((https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2)\)/g;

// One stylesheet per family; scripts/build-site.mjs links mono plus the one sans family a page's language needs.
export const FONT_FAMILIES = {
  mono: "IBM+Plex+Mono:wght@400;500;600",
  sc: `Noto+Sans+SC:wght@${CJK_WEIGHTS}`,
  tc: `Noto+Sans+TC:wght@${CJK_WEIGHTS}`,
  jp: `Noto+Sans+JP:wght@${CJK_WEIGHTS}`,
  kr: `Noto+Sans+KR:wght@${CJK_WEIGHTS}`
};

// Noto CJK is a variable font: Google repeats every slice once per weight with the same file. One rule per slice
// with a weight range says the same in a fifth of the CSS.
function mergeWeights(css) {
  const faces = new Map();
  for (const [, body] of css.matchAll(/@font-face\s*\{([^}]*)\}/g)) {
    const prop = (name) => body.match(new RegExp(`${name}:\\s*([^;]+);`))?.[1].trim();
    const key = [prop("font-family"), prop("font-style"), prop("src"), prop("unicode-range")].join("|");
    const weight = Number(prop("font-weight"));
    const face = faces.get(key) || { family: prop("font-family"), style: prop("font-style"), src: prop("src"), range: prop("unicode-range"), min: weight, max: weight };
    face.min = Math.min(face.min, weight);
    face.max = Math.max(face.max, weight);
    faces.set(key, face);
  }
  return [...faces.values()].map((face) => `@font-face{font-family:${face.family};font-style:${face.style};font-weight:${face.min === face.max ? face.min : `${face.min} ${face.max}`};font-display:swap;src:${face.src};${face.range ? `unicode-range:${face.range};` : ""}}`).join("\n");
}

async function fetchWithRetry(url, as) {
  for (let attempt = 1; ; attempt += 1) {
    try {
      const response = await fetch(url, { headers: { "user-agent": USER_AGENT } });
      if (!response.ok) throw new Error(`${response.status} ${url}`);
      return as === "text" ? await response.text() : Buffer.from(await response.arrayBuffer());
    } catch (error) {
      if (attempt >= 4) throw error;
      await new Promise((resolve) => setTimeout(resolve, attempt * 1000));
    }
  }
}

async function pool(items, size, fn) {
  let next = 0;
  await Promise.all(Array.from({ length: size }, async () => {
    while (next < items.length) await fn(items[next++]);
  }));
}

export async function mirrorFonts() {
  fs.mkdirSync(out, { recursive: true });
  const sheets = {};
  const sources = new Map();
  for (const [key, family] of Object.entries(FONT_FAMILIES)) {
    sheets[key] = mergeWeights(await fetchWithRetry(`https://fonts.googleapis.com/css2?family=${family}&display=swap`, "text"));
    for (const [, url] of sheets[key].matchAll(GSTATIC_URL)) sources.set(url, null);
  }
  // Content-addressed names: a changed font gets a new URL, so R2 can cache every file as immutable.
  await pool([...sources.keys()], 16, async (url) => {
    const bytes = await fetchWithRetry(url);
    const name = `${crypto.createHash("sha256").update(bytes).digest("hex").slice(0, 20)}.woff2`;
    fs.writeFileSync(path.join(out, name), bytes);
    sources.set(url, { name, size: bytes.length });
  });
  let faces = 0;
  const sizes = {};
  for (const [key, css] of Object.entries(sheets)) {
    const text = `/* Generated by scripts/mirror-fonts.mjs from Google Fonts (SIL Open Font License); the files are served from R2. */\n${
      css.replace(GSTATIC_URL, (_, url) => `url(${PUBLIC_BASE}${sources.get(url).name})`)}\n`;
    fs.writeFileSync(path.join(root, "site", `fonts-${key}.css`), text);
    faces += (text.match(/@font-face/g) || []).length;
    sizes[key] = text.length;
  }
  const files = new Map([...sources.values()].map((item) => [item.name, item.size]));
  return { files: files.size, bytes: [...files.values()].reduce((sum, size) => sum + size, 0), faces, sizes };
}

// wrangler with stdin closed (an open pipe can leave it waiting); on Windows npx is a .cmd that needs a shell,
// so arguments are quoted for it.
function wrangler(args) {
  const windows = process.platform === "win32";
  const quoted = windows ? args.map((arg) => (/[\s,]/.test(arg) ? `"${arg}"` : arg)) : args;
  return new Promise((resolve, reject) => {
    const child = spawn(windows ? "npx.cmd" : "npx", ["wrangler@4", ...quoted], { stdio: ["ignore", "pipe", "pipe"], shell: windows });
    let output = "";
    child.stdout.on("data", (chunk) => { output += chunk; });
    child.stderr.on("data", (chunk) => { output += chunk; });
    child.on("error", reject);
    child.on("close", (code) => (code === 0 ? resolve(output) : reject(new Error(`wrangler exited with ${code}: ${output.slice(-300)}`))));
  });
}

// Uploads what R2 does not serve yet, so an interrupted upload can simply be run again.
export async function uploadFonts() {
  const names = fs.readdirSync(out).filter((name) => name.endsWith(".woff2"));
  const missing = [];
  await pool(names, 24, async (name) => {
    try {
      const response = await fetch(`${PUBLIC_BASE}${name}`, { method: "HEAD" });
      if (response.ok && Number(response.headers.get("content-length")) === fs.statSync(path.join(out, name)).size) return;
    } catch {}
    missing.push(name);
  });
  console.log(`${names.length - missing.length} of ${names.length} fonts already on R2; uploading ${missing.length}.`);
  let done = 0;
  await pool(missing, 16, async (name) => {
    for (let attempt = 1; ; attempt += 1) {
      try {
        await wrangler(["r2", "object", "put", `${BUCKET}/${PREFIX}${name}`, "--remote", "--file", path.join(out, name),
          "--content-type", "font/woff2", "--cache-control", "public, max-age=31536000, immutable"]);
        break;
      } catch (error) {
        if (attempt >= 3) throw error;
      }
    }
    done += 1;
    if (done % 50 === 0 || done === missing.length) console.log(`Uploaded ${done}/${missing.length}`);
  });
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { files, bytes, faces, sizes } = await mirrorFonts();
  console.log(`${faces} @font-face rules, ${files} woff2 files, ${(bytes / 1024 / 1024).toFixed(1)} MB in ${path.relative(root, out)}/`);
  console.log(`Stylesheets: ${Object.entries(sizes).map(([key, size]) => `fonts-${key}.css ${(size / 1024).toFixed(0)} KB`).join(", ")}`);
  if (process.argv.includes("--upload")) await uploadFonts();
}
